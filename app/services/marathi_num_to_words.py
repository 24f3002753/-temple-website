HUNDREDS = {
    1: "एकशे", 2: "दोनशे", 3: "तीनशे", 4: "चारशे", 5: "पाचशे",
    6: "सहाशे", 7: "सातशे", 8: "आठशे", 9: "नऊशे"
}

def number_to_marathi_words(num: int) -> str:
    """
    पूर्णांक संख्येचे शुद्ध मराठी शब्दात रूपांतर
    उदा. 501 -> 'पाचशे एक रुपये फक्त'
    """
    if num == 0:
        return "शून्य रुपये फक्त"

    try:
        num = int(num)
    except (ValueError, TypeError):
        return ""

    if num < 0:
        return "ऋण " + number_to_marathi_words(abs(num))

    parts = []

    # १. कोटी (Crores) >= 1,00,00,000
    if num >= 10000000:
        crores = num // 10000000
        num %= 10000000
        parts.append(f"{ONES_AND_TEENS.get(crores, str(crores))} कोटी")

    # २. लाख (Lakhs) >= 1,00,000
    if num >= 100000:
        lakhs = num // 100000
        num %= 100000
        parts.append(f"{ONES_AND_TEENS.get(lakhs, str(lakhs))} लाख")

    # ३. हजार (Thousands) >= 1,000
    if num >= 1000:
        thousands = num // 1000
        num %= 1000
        parts.append(f"{ONES_AND_TEENS.get(thousands, str(thousands))} हजार")

    # ४. शेकडा (Hundreds) >= 100
    if num >= 100:
        hundreds = num // 100
        num %= 100
        parts.append(HUNDREDS.get(hundreds, f"{hundreds}शे"))

    # ५. शेवटचे दोन अंक (Tens & Units)
    if num > 0:
        parts.append(ONES_AND_TEENS.get(num, str(num)))

    result = " ".join(p for p in parts if p).strip()
    return f"{result} रुपये फक्त"
